"""Build a small upload bundle for Google Colab.

Why: the full prepared dataset is ~176 MB. Colab uploads are more reliable with a
smaller file. Images are resized so their longest side is at most `--max-side`
pixels. YOLO labels are normalized (0..1), so resizing does NOT change them.

Output:
    data/raw/colab_bundle/plates/...   (resized images + labels + data.yaml)
    data/raw/plates_colab.zip          (upload this file to Colab)

Run from the project root:

    python scripts/make_colab_bundle.py
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from PIL import Image

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = PROJECT_ROOT / "data" / "raw" / "plates"
DEFAULT_OUTPUT = PROJECT_ROOT / "data" / "raw" / "colab_bundle"
DEFAULT_ZIP = PROJECT_ROOT / "data" / "raw" / "plates_colab.zip"

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--zip", type=Path, default=DEFAULT_ZIP)
    parser.add_argument("--max-side", type=int, default=640)
    parser.add_argument("--quality", type=int, default=90)
    return parser.parse_args()


def folder_size_mb(path: Path) -> float:
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file()) / 1e6


def main() -> None:
    args = parse_args()
    source = args.source.resolve()
    output = args.output.resolve()
    zip_path = args.zip.resolve()
    plates = output / "plates"

    if not (source / "images" / "train").is_dir():
        raise SystemExit(f"Prepared dataset not found: {source}")

    if output.exists():
        shutil.rmtree(output)

    for split in ("train", "val"):
        image_dir = plates / "images" / split
        label_dir = plates / "labels" / split
        image_dir.mkdir(parents=True, exist_ok=True)
        label_dir.mkdir(parents=True, exist_ok=True)

        images = sorted(
            p for p in (source / "images" / split).iterdir()
            if p.suffix.lower() in IMAGE_EXTENSIONS
        )

        for image_path in images:
            target = image_dir / (image_path.stem + ".jpg")
            with Image.open(image_path) as image:
                image = image.convert("RGB")
                image.thumbnail((args.max_side, args.max_side), Image.LANCZOS)
                image.save(target, "JPEG", quality=args.quality, optimize=True)

            label_path = source / "labels" / split / (image_path.stem + ".txt")
            if not label_path.is_file():
                raise SystemExit(f"Missing label: {label_path}")
            shutil.copy2(label_path, label_dir / label_path.name)

        print(f"{split}: {len(images)} images + labels")

    (plates / "data.yaml").write_text(
        "# Generated by scripts/make_colab_bundle.py\n"
        "path: /content/data/plates\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n"
        "  0: license_plate\n",
        encoding="utf-8",
    )

    if zip_path.exists():
        zip_path.unlink()
    shutil.make_archive(str(zip_path.with_suffix("")), "zip", root_dir=str(output))

    print(f"Bundle folder: {output}  ({folder_size_mb(output):.1f} MB)")
    print(f"Upload file  : {zip_path}  ({zip_path.stat().st_size / 1e6:.1f} MB)")
    print("Upload this zip to Colab. The notebook extracts it to /content/data/plates")


if __name__ == "__main__":
    main()
