"""Convert the raw Moroccan plate dataset into a standard YOLO layout.

Input (already on disk):
    data/raw/data_car/dataset/dataset/
        IMG_0001.jpg
        IMG_0001.txt
        ...

Output:
    data/raw/plates/
    ├── images/
    │   ├── train/
    │   └── val/
    ├── labels/
    │   ├── train/
    │   └── val/
    └── data.yaml

Run from the project root:

    python scripts/prepare_dataset.py            # do the conversion
    python scripts/prepare_dataset.py --dry-run  # only validate, copy nothing

The script never deletes or modifies the original files. It copies them.
"""

from __future__ import annotations

import argparse
import random
import shutil
from collections import Counter
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = PROJECT_ROOT / "data" / "raw" / "data_car" / "dataset" / "dataset"
DEFAULT_OUTPUT = PROJECT_ROOT / "data" / "raw" / "plates"

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--val-fraction", type=float, default=0.2)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def validate_label(label_path: Path) -> str | None:
    """Return an error message, or None if the YOLO label is valid."""
    lines = [line.strip() for line in label_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not lines:
        return "empty label file"

    for line in lines:
        parts = line.split()
        if len(parts) != 5:
            return f"expected 5 fields, got {len(parts)}"

        try:
            class_id = int(parts[0])
            x_center, y_center, width, height = (float(value) for value in parts[1:])
        except ValueError:
            return "non-numeric value"

        if class_id != 0:
            return f"unexpected class id {class_id} (expected 0 = license_plate)"
        if not (0 <= x_center <= 1 and 0 <= y_center <= 1):
            return "centre coordinates outside [0, 1]"
        if not (0 < width <= 1 and 0 < height <= 1):
            return "width/height outside (0, 1]"

    return None


def collect_pairs(source: Path) -> tuple[list[tuple[Path, Path]], list[str]]:
    """Find image/label pairs and collect validation problems."""
    images = sorted(p for p in source.rglob("*") if p.suffix.lower() in IMAGE_EXTENSIONS)
    image_by_stem = {path.stem: path for path in images}

    pairs: list[tuple[Path, Path]] = []
    problems: list[str] = []

    for stem, image_path in sorted(image_by_stem.items()):
        label_path = image_path.with_suffix(".txt")
        if not label_path.is_file():
            problems.append(f"missing label: {image_path.name}")
            continue

        error = validate_label(label_path)
        if error:
            problems.append(f"invalid label {label_path.name}: {error}")
            continue

        pairs.append((image_path, label_path))

    label_stems = {p.stem for p in source.rglob("*.txt")}
    for stem in sorted(label_stems - set(image_by_stem)):
        problems.append(f"label without image: {stem}.txt")

    return pairs, problems


def copy_pair(image_path: Path, label_path: Path, split: str, output: Path) -> None:
    image_dir = output / "images" / split
    label_dir = output / "labels" / split
    image_dir.mkdir(parents=True, exist_ok=True)
    label_dir.mkdir(parents=True, exist_ok=True)

    target_image = image_dir / image_path.name
    target_label = label_dir / label_path.name

    if not target_image.exists():
        shutil.copy2(image_path, target_image)
    if not target_label.exists():
        shutil.copy2(label_path, target_label)


def write_data_yaml(output: Path, class_name: str) -> Path:
    yaml_path = output / "data.yaml"
    content = (
        "# Generated by scripts/prepare_dataset.py\n"
        f"path: {output.resolve()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n"
        f"  0: {class_name}\n"
    )
    yaml_path.write_text(content, encoding="utf-8")
    return yaml_path


def main() -> None:
    args = parse_args()
    source = args.source.resolve()
    output = args.output.resolve()

    if not source.is_dir():
        raise SystemExit(f"Source folder not found: {source}")
    if not 0 < args.val_fraction < 1:
        raise SystemExit("--val-fraction must be between 0 and 1")

    pairs, problems = collect_pairs(source)
    if not pairs:
        raise SystemExit(f"No valid image/label pairs found in {source}")

    random.Random(args.seed).shuffle(pairs)
    val_count = max(1, round(len(pairs) * args.val_fraction))
    val_pairs = pairs[:val_count]
    train_pairs = pairs[val_count:]

    print(f"Source       : {source}")
    print(f"Valid pairs  : {len(pairs)}")
    print(f"Train / Val  : {len(train_pairs)} / {len(val_pairs)}")
    print(f"Problems     : {len(problems)}")

    for problem in problems[:10]:
        print(f"  - {problem}")
    if len(problems) > 10:
        print(f"  ... and {len(problems) - 10} more")

    if args.dry_run:
        print("\nDry run: no files copied, no data.yaml written.")
        return

    for image_path, label_path in train_pairs:
        copy_pair(image_path, label_path, "train", output)
    for image_path, label_path in val_pairs:
        copy_pair(image_path, label_path, "val", output)

    yaml_path = write_data_yaml(output, "license_plate")

    print("\nCreated:")
    print(f"  {output / 'images' / 'train'}  ({len(train_pairs)} images)")
    print(f"  {output / 'images' / 'val'}    ({len(val_pairs)} images)")
    print(f"  {yaml_path}")
    print("\nNext: train with")
    print("  yolo detect train data=data/raw/plates/data.yaml \\")
    print("    model=yolo11n.pt epochs=50 imgsz=416 batch=2 device=cpu")


if __name__ == "__main__":
    main()
